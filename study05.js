//Loop/Repeat/Iteration Statement
//while, do-while, for

let x = 1;

while(x <= 5){
    console.log("Hello World");
    ++x;
}

//======================================
let y = 1;

do{
    console.log(`${y} hello world`);
    ++y;
}while(y <= 5);

//======================================

for(let i = 1; i <= 5; ++i){
    console.log('${i} hello world');
}